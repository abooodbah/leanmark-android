#!/bin/sh
# Copies the reader page, the Markdown core and their pinned packages from a
# checkout of the desktop app, then rewrites third_party/reader-assets.sha256.
#
#   scripts/update-reader-assets.sh /path/to/leanmark
#
# The desktop checkout needs `npm ci` first, for Mermaid and the fonts.
set -eu

desktop=${1:?usage: scripts/update-reader-assets.sh /path/to/leanmark}
here=$(cd "$(dirname "$0")/.." && pwd)
assets="$here/app/src/main/assets/reader"
cpp="$here/app/src/main/cpp"
modules="$desktop/node_modules"

mkdir -p "$assets/vendor" "$assets/fonts" "$cpp/core" "$cpp/md4c"
cp "$desktop/assets/reader.css" "$desktop/assets/reader.js" "$assets/"
# The only change to the desktop page: load the Android bridge before reader.js.
sed 's|^    <script src="/reader.js" defer></script>$|    <script src="/android-host.js"></script>\n&|' \
  "$desktop/assets/reader.html" > "$assets/reader.html"
grep -q 'src="/android-host.js"' "$assets/reader.html"
cp "$modules/mermaid/dist/mermaid.min.js" "$assets/vendor/"
for font in \
  ibm-plex-sans/files/ibm-plex-sans-latin-400-normal \
  ibm-plex-sans/files/ibm-plex-sans-latin-500-normal \
  ibm-plex-sans/files/ibm-plex-sans-latin-600-normal \
  ibm-plex-serif/files/ibm-plex-serif-latin-600-normal \
  ibm-plex-mono/files/ibm-plex-mono-latin-400-normal; do
  cp "$modules/@fontsource/$font.woff2" "$assets/fonts/"
done
cp "$desktop/src/core/MarkdownCore.h" "$desktop/src/core/MarkdownCore.cpp" "$cpp/core/"
for file in md4c.c md4c.h md4c-html.c md4c-html.h entity.c entity.h LICENSE.md; do
  cp "$desktop/third_party/md4c/$file" "$cpp/md4c/"
done
cp "$desktop/tests/linux/CoreTests.cpp" "$here/native-tests/"

cd "$here"
{
  echo "# Generated by scripts/update-reader-assets.sh from desktop commit $(git -C "$desktop" rev-parse HEAD)"
  find app/src/main/assets/reader app/src/main/cpp/core app/src/main/cpp/md4c native-tests/CoreTests.cpp \
    -type f ! -name android-host.js | LC_ALL=C sort | xargs sha256sum
} > third_party/reader-assets.sha256
echo "Updated. Review the diff, then run the tests."
